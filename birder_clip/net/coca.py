class CoCaAttentionPool(nn.Module):
    """
    Adapted from:
    https://github.com/mlfoundations/open_clip/blob/main/src/open_clip/transformer.py
    """

    def __init__(
        self,
        dim: int,
        context_dim: int,
        num_heads: int,
        latent_len: int = 256,
        qkv_bias: bool = True,
        norm_eps: float = 1e-5,
    ) -> None:
        super().__init__()
        assert dim % num_heads == 0
        self.dim = dim
        self.num_heads = num_heads
        self.head_dim = dim // num_heads
        self.scale = self.head_dim**-0.5

        self.latent_len = latent_len
        self.latent = nn.Parameter(torch.empty(1, self.latent_len, dim))

        self.q = nn.Linear(dim, dim, bias=qkv_bias)
        self.kv = nn.Linear(context_dim, dim * 2, bias=qkv_bias)
        self.proj = nn.Linear(dim, dim)

        self.latent_norm = nn.LayerNorm(dim, eps=norm_eps)
        self.context_norm = nn.LayerNorm(context_dim, eps=norm_eps)

        # Weight initialization
        nn.init.normal_(self.latent)
        nn.init.xavier_uniform_(self.q.weight)
        nn.init.xavier_uniform_(self.kv.weight)
        nn.init.xavier_uniform_(self.proj.weight)
        if self.q.bias is not None:
            nn.init.zeros_(self.q.bias)
            nn.init.zeros_(self.kv.bias)

        nn.init.zeros_(self.proj.bias)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        B, N, _ = x.size()

        x = self.context_norm(x)
        q_latent = self.latent_norm(self.latent.expand(B, self.latent_len, -1))
        q = self.q(q_latent).reshape(B, self.latent_len, self.num_heads, self.head_dim).transpose(1, 2)

        kv = self.kv(x).reshape(B, N, 2, self.num_heads, self.head_dim).permute(2, 0, 3, 1, 4)
        k, v = kv.unbind(0)

        x = F.scaled_dot_product_attention(q, k, v, scale=self.scale)  # pylint: disable=not-callable
        x = x.transpose(1, 2).reshape(B, self.latent_len, self.dim)
        x = self.proj(x)

        return x


